public class Execicio22 {
    static void main(String[] args) {

        double nota = 8;

        if (nota >= 9) {
            System.out.println("Exelente");
        } else if (nota >= 7) {
            System.out.println("Bom");
        } else if (nota >= 5) {
            System.out.println("Recuperação");
        } else {
            System.out.println("Reprovado");
        }

    }
}
